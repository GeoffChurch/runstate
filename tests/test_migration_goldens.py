class _M10Reader:
    """mycooc's reading of its reclaim tool's malformed body (M10): a release, read as
    ``preempted``, of the claim it names; one naming none ends nothing. A well-formed
    ``stopped`` is its worker's own, unless such a release of its claim came first,
    when it is the repair script's note; a value is a metric."""

    def __init__(self, log):
        self._malformed: dict[int, int | None] = {}
        self._notes: set[int] = set()
        for x in log:
            if x.topic != "lifecycle.stopped":
                continue
            body = json.loads(x.body)
            if "completed" not in body:
                self._malformed[x.seq] = body["claim_seq"]
            elif body["claim_seq"] in self._malformed.values():
                self._notes.add(x.seq)

    def started(self, seq):
        return frozenset({"ref"})

    def stopped(self, seq):
        if seq in self._malformed:
            act = (
                V.Note()
                if self._malformed[seq] is None
                else V.Release(V.Outcome.PREEMPTED)
            )
            return frozenset({V.ThirdStop("reclaim", act)})
        if seq in self._notes:
            return frozenset({V.ThirdStop("tp", V.Note())})
        return frozenset({V.OwnStop()})

    def value(self, seq):
        return REFERENCE.classifier.value(seq)


class M10Classifier:
    def read(self, log):
        return _M10Reader(log)


M10 = REFERENCE._replace(
    # the claims resumed from checkpoints the log does not hold
    workers={
        "ref": dataclasses.replace(
            REFERENCE.workers["ref"],
            load=REFERENCE.workers["ref"].load | {V.Load.OUTSIDE},
            # its exits list the stops its ticks drained, or every one it took in
            honored=frozenset(V.Honored),
        )
    },
    third_parties={
        "tp": REFERENCE.third_parties["tp"],
        # the reclaim tool reports a death only while the claim is held (D2)
        "reclaim": dataclasses.replace(
            UNSTATED.third_parties["any"], via=frozenset({V.Via.IF_HELD})
        ),
    },
    classifier=M10Classifier(),
)

_HISTORY = {id(rows): h for rows, h in S.GOLDENS.values()}
MALFORMED = ("reclaimed", "later_release", "claimless_release")


def _history(h):
    """The manifest a golden's run carries: an entry of the earlier step when its log
    was born in 0.2.0."""
    if h is None or h.born is H.Born.V0_3_0:
        return ()
    return (
        Entry(
            run_id="golden",
            from_format="0.2.0",
            to_format="0.3.0",
            runstate="test",
            step_source="sha256:0",
            at=0.0,
            limits=LIMITS,
            assumed=None,
            facts=None,
            resolved={"record-claim": "positional", "stop-honored": "positional"},
            readings={},
            accepted={},
        ),
    )


def facts(rid):
    """A golden's stated facts: its history's, else (M10's three) the hand-stated."""
    h = _HISTORY.get(id(G.GOLDEN[rid]))
    if h is None:
        assert rid in MALFORMED
        return M10, ()
    return D.configuration([D.observe(h)]), _history(h)


def _key(rows):
    """A log as a classifier sees it, whatever ``created_at`` a store gave it."""
    return tuple((x.seq, x.topic, x.name, x.request_id, x.body) for x in rows)


class _Prefixed:
    """A golden's own reader, its versions and writers named under its id."""

    def __init__(self, rid, inner):
        self._rid = rid
        self._inner = inner

    def started(self, seq):
        return frozenset(f"{self._rid}:{v}" for v in self._inner.started(seq))

    def stopped(self, seq):
        return frozenset(
            (
                V.ThirdStop(f"{self._rid}:{a.writer}", a.act)
                if isinstance(a, V.ThirdStop)
                else a
            )
            for a in self._inner.stopped(seq)
        )

    def value(self, seq):
        return self._inner.value(seq)


class _Plain:
    """Any other log, as the reference Worker alone wrote it: every claim its, every
    ``stopped`` its own, a value with a step a metric, one without a register."""

    def __init__(self, log):
        self._stepless = {
            x.seq
            for x in log
            if x.topic == "value" and json.loads(x.body)["step"] is None
        }

    def started(self, seq):
        return frozenset({"ref"})

    def stopped(self, seq):
        return frozenset({V.OwnStop()})

    def value(self, seq):
        if seq in self._stepless:
            return frozenset({V.ValueRole(V.Role.PASS, True)})
        return REFERENCE.classifier.value(seq)


class _ByGolden:
    """Every golden's facts in one configuration, for the corpus runner, which takes
    one ``--assume`` for a root: the classifier knows each golden by its log and
    answers as that golden's own classifier, under its id; any other log it reads as
    the reference Worker's alone (``_Plain``), under the reference facts."""

    def __init__(self):
        self._by = {_key(G.GOLDEN[rid]): rid for rid in G.GOLDEN}

    def read(self, log):
        rid = self._by.get(_key(log))
        if rid is None:  # no golden: a plain worker's log
            return _Plain(log)
        configuration, _ = facts(rid)
        return _Prefixed(rid, configuration.classifier.read(log))


def _every_golden():
    workers, third = dict(REFERENCE.workers), dict(REFERENCE.third_parties)
    for rid in G.GOLDEN:
        configuration, _ = facts(rid)
        workers |= {f"{rid}:{k}": f for k, f in configuration.workers.items()}
        third |= {f"{rid}:{k}": f for k, f in configuration.third_parties.items()}
    return V.Configuration(workers, third, _ByGolden())


GOLDENS_CONFIGURATION = _every_golden()
"""Each golden's facts, for ``--assume tests.test_migration_goldens:GOLDENS_CONFIGURATION``
in the corpus runner's tests; every golden is born in 0.3.0."""


def migrated(rid):
    configuration, history = facts(rid)
    res = Resolutions(Assumptions(configuration, "golden", LIMITS), CHOICES)
    return step.transform(list(G.GOLDEN[rid]), resolutions=res, history=history)


def written(rid):
    return [
        (x.seq, x.topic, x.name, x.request_id, json.loads(x.body))
        for x in migrated(rid).rows
    ]


def test_every_golden_is_restated():
    assert sorted(OUTPUT) == sorted(G.GOLDEN)
    assert sorted(DIVERGED) == sorted(G.GOLDEN)


@pytest.mark.parametrize("rid", list(G.GOLDEN))
def test_each_goldens_output_is_pinned(rid):
    assert written(rid) == OUTPUT[rid]


@pytest.mark.parametrize("rid", list(G.GOLDEN))
def test_each_goldens_divergences_are_pinned(rid):
    fired = {k: list(v) for k, v in migrated(rid).divergences.items() if v}
    assert fired == DIVERGED[rid]


@pytest.mark.parametrize("rid", MALFORMED)
def test_a_malformed_golden_is_refused_under_no_stated_facts(rid):
    res = Resolutions(Assumptions(UNSTATED, None, LIMITS), CHOICES)
    with pytest.raises(MigrationError, match="only a consumer's classifier may read"):
        step.transform(list(G.GOLDEN[rid]), resolutions=res, history=())


def _schema_errors(row):
    """The 0.4.0 stack's errors for a row: the envelope's, and its convention's
    when 0.4.0 owns its topic; a user topic answers to the envelope alone."""
    pytest.importorskip("jsonschema")
    from test_schema_v0_4_0 import STACK_0_4_0, row_errors

    if row.topic == "value" or row.topic.startswith(
        ("lifecycle.", "control.", "supervisor.")
    ):
        return row_errors(row)
    record = row._asdict() | {"body": json.loads(row.body)}
    del record["created_at"]
    return [e.message for e in STACK_0_4_0.envelope.iter_errors(record)]


@pytest.mark.parametrize("rid", list(G.GOLDEN))
def test_every_goldens_rows_are_0_4_0s(rid):
    out = migrated(rid).rows
    assert [x.seq for x in out] == list(range(1, len(out) + 1))
    errors = {x.seq: _schema_errors(x) for x in out}
    assert {seq: e for seq, e in errors.items() if e} == {}


