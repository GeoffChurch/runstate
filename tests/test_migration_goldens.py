"""The 0.3.0 -> 0.4.0 step's goldens, restated (the plan's Task 22): each golden log,
its writers' facts, the choices, and the step's whole output, pinned.

**The facts** of a golden are those its simulator history declares
(``tests/migration_derive.py``): the history is the golden's account of what its
writers did, so its facts are the consumer's statement for it. The three goldens whose
``stopped`` has M10's malformed body have no history, since no conforming writer writes
one; they are stated by hand (``M10``), with a classifier that reads the body as
mycooc's reclaim tool meant it, as only a consumer's classifier may
(log-formats.md §6). Under no stated facts the step refuses them.

**The choices** are the same for every golden (``CHOICES``): ``span=fewest``,
``origin=newest``, ``end-time=lower``, and ``end`` left to ``refuse``, which no golden
forks.

With the oracle and the mutation test, this module imports both the step and the
simulator: it is a harness module, never one the step or the simulator imports.
"""

